// Art imported in the studio. An image is kept in memory until the next save,
// while records already point at its final path inside the mod:
//   mods/<mod>/assets/studio/<name>_<hash>.png
// The content hash in the name means a replaced image never reuses a cached
// file, and saving the same image twice writes one file. On save, pending
// images are written and studio images nothing references are removed (only
// in assets/studio/, never the mod's own files).

import type { Host } from "../host/types.ts";

export const STUDIO_ASSETS = "assets/studio";

const pending = new Map<string, { data: Uint8Array; url: string }>();

function hash(data: Uint8Array): string {
  // FNV-1a, 32 bit: names files, not a security boundary
  let h = 0x811c9dc5;
  for (const b of data) h = Math.imul(h ^ b, 0x01000193) >>> 0;
  return h.toString(16).padStart(8, "0");
}

// file types the studio imports, by extension: PNG art; cries and other
// sounds in the formats LÖVE plays
export const ASSET_TYPES: Record<string, string> = {
  png: "image/png",
  wav: "audio/wav",
  ogg: "audio/ogg",
  mp3: "audio/mpeg",
  flac: "audio/flac",
};

// Registers an imported file for `mod` and returns the path records use.
export function addAsset(mod: string, name: string, data: Uint8Array, ext = "png"): string {
  const safe = name.toLowerCase().replace(/[^a-z0-9_]+/g, "_").replace(/^_+|_+$/g, "") || "art";
  const path = `mods/${mod}/${STUDIO_ASSETS}/${safe}_${hash(data)}.${ext}`;
  if (!pending.has(path)) pending.set(path, { data, url: URL.createObjectURL(new Blob([data as BlobPart], { type: ASSET_TYPES[ext] ?? "application/octet-stream" })) });
  return path;
}

// A URL for an asset path: the in-memory copy if not saved yet; a derived
// copy of vanilla art shows the vanilla file it is made from.
export function assetUrl(host: Host, version: string, path: string | undefined): string {
  if (!path) return "";
  const pend = pending.get(path)?.url;
  if (pend) return pend;
  const source = derivedSource(path);
  return host.imageUrl(version, source ?? path);
}

// ------------------------------------------------------------------ derived art
// A mod may not point at the ROM-derived cache (modkit MK301), but it may
// ship a recipe (manifest "assets_transforms") that copies cache art into
// save/mod-derived/<mod>/ when the game loads. The studio keeps its copies
// under studio/ there (so they never shadow the cache paths) and writes the
// recipe from the paths its saved file uses.

export const STUDIO_TRANSFORMS = "studio_transforms.lua";
const CACHE = "assets/generated/";
const DERIVED = /^save\/mod-derived\/[^/]+\/studio\/(.+)$/;

export function isCachePath(path: unknown): path is string {
  return typeof path === "string" && path.startsWith(CACHE);
}

// save/mod-derived/<mod>/studio/<rel> for a cache path
export function derivedPath(mod: string, cachePath: string): string {
  return `save/mod-derived/${mod}/studio/${cachePath.slice(CACHE.length)}`;
}

// the cache file a studio-derived path is copied from
export function derivedSource(path: string): string | null {
  const m = DERIVED.exec(path);
  return m ? CACHE + m[1] : null;
}

// An extended tileset's sheet: the player's own sheet (`source`, relative to
// the cache) with the mod's tiles below it, `per` tiles a row. Tiles are 64
// shade digits (0 white .. 3 black, the importer's grays).
export interface SheetRecipe {
  source: string;
  out: string;
  per: number;
  tiles: string[];
  // animated tiles: one 8x8 image per frame (shade digits)
  frames?: { out: string; tile: string }[];
  // cache art the extension's animations need copied (the flower frames)
  copies?: string[];
}

function recipe(mod: string, rels: string[], sheets: SheetRecipe[] = []): string {
  const lines = [
    `-- ${mod}: generated by gen1recomp-studio (asset transforms). Do not hand-edit;`,
    "-- it is rewritten on every save from the art studio_content.lua uses.",
    "-- Copies the player's own imported art; the mod ships no ROM pixels.",
    "local COPIES = {",
    ...rels.map((r) => `  ${JSON.stringify(r)},`),
    "}",
  ];
  if (sheets.length) {
    lines.push(
      "",
      "-- tilesets the mod extends: the player's own sheet with the mod's tiles",
      "-- below it (64 shade digits per tile, 0 white .. 3 black)",
      "local SHEETS = {",
      ...sheets.flatMap((s) => [
        "  {",
        `    source = ${JSON.stringify(s.source)}, out = ${JSON.stringify(s.out)}, per = ${s.per},`,
        "    tiles = {",
        ...s.tiles.map((t) => `      ${JSON.stringify(t)},`),
        "    },",
        ...(s.frames?.length
          ? ["    frames = {", ...s.frames.map((f) => `      { out = ${JSON.stringify(f.out)}, tile = ${JSON.stringify(f.tile)} },`), "    },"]
          : []),
        "  },",
      ]),
      "}",
      "local SHADE = { 1, 2 / 3, 1 / 3, 0 }",
      "local function paint(img, tx, ty, digits)",
      "  for p = 0, 63 do",
      "    local v = SHADE[(tonumber(digits:sub(p + 1, p + 1)) or 0) + 1]",
      "    img:setPixel(tx + p % 8, ty + math.floor(p / 8), v, v, v, 1)",
      "  end",
      "end",
    );
  }
  lines.push(
    "",
    "return function(ctx)",
    "  for _, rel in ipairs(COPIES) do",
    "    if ctx.exists(rel) then ctx.writeImage(ctx.readImage(rel), \"studio/\" .. rel) end",
    "  end",
  );
  if (sheets.length) {
    lines.push(
      "  for _, s in ipairs(SHEETS) do",
      "    if #s.tiles > 0 and ctx.exists(s.source) then",
      "      local src = ctx.readImage(s.source)",
      "      local w, h = src:getWidth(), src:getHeight()",
      "      local img = ctx.blank(w, h + math.ceil(#s.tiles / s.per) * 8, 1, 1, 1, 1)",
      "      ctx.blit(img, src, 0, 0)",
      "      for i, digits in ipairs(s.tiles) do",
      "        paint(img, ((i - 1) % s.per) * 8, h + math.floor((i - 1) / s.per) * 8, digits)",
      "      end",
      "      ctx.writeImage(img, s.out)",
      "    end",
      "    for _, f in ipairs(s.frames or {}) do",
      "      local img = ctx.blank(8, 8, 1, 1, 1, 1)",
      "      paint(img, 0, 0, f.tile)",
      "      ctx.writeImage(img, f.out)",
      "    end",
      "  end",
    );
  }
  lines.push("end", "");
  return lines.join("\n");
}

// Rewrites the recipe (and the manifest entry for it) from the derived paths
// the saved studio file uses and the tileset sheets to build; removes both
// when nothing needs them. A mod with its own transforms file is left alone.
export async function syncTransforms(host: Host, mod: string, referenced: string, sheets: SheetRecipe[] = []): Promise<{ copies: number; blocked: boolean }> {
  const built = new Set(sheets.flatMap((s) => [s.out, ...(s.frames ?? []).map((f) => f.out)]));
  const found = [...referenced.matchAll(new RegExp(`save/mod-derived/${mod}/studio/([^"\\s]+)`, "g"))].map((m) => m[1]);
  const rels = [...new Set([...found, ...sheets.flatMap((s) => s.copies ?? [])])]
    .filter((r) => !r.endsWith("/") && !built.has(`studio/${r}`))
    .sort();
  const manifestPath = `mods/${mod}/manifest.json`;
  const text = await host.readText("game", manifestPath);
  if (text === null) return { copies: 0, blocked: false };
  const manifest = JSON.parse(text) as Record<string, unknown>;
  const current = manifest.assets_transforms;
  if (current !== undefined && current !== STUDIO_TRANSFORMS) return { copies: 0, blocked: rels.length + sheets.length > 0 };
  if (rels.length || sheets.length) {
    await host.writeText(`mods/${mod}/${STUDIO_TRANSFORMS}`, recipe(mod, rels, sheets));
    if (current !== STUDIO_TRANSFORMS) {
      manifest.assets_transforms = STUDIO_TRANSFORMS;
      await host.writeText(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
    }
  } else if (current === STUDIO_TRANSFORMS) {
    delete manifest.assets_transforms;
    await host.writeText(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
    await host.deleteFile(`mods/${mod}/${STUDIO_TRANSFORMS}`);
  }
  return { copies: rels.length, blocked: false };
}


// Writes the pending images of `mod`, then removes studio images of the mod
// that `referenced` (the saved studio file) no longer mentions.
export async function saveAssets(host: Host, mod: string, referenced: string): Promise<{ written: number; removed: number }> {
  let written = 0;
  let removed = 0;
  const prefix = `mods/${mod}/${STUDIO_ASSETS}/`;
  for (const [path, entry] of pending) {
    if (!path.startsWith(prefix) || !referenced.includes(path)) continue;
    await host.writeBinary(path, entry.data);
    written++;
  }
  for (const e of await host.list("game", prefix.slice(0, -1))) {
    if (e.dir || !(e.name.split(".").pop()! in ASSET_TYPES)) continue;
    const path = prefix + e.name;
    if (referenced.includes(path)) continue;
    await host.deleteFile(path);
    removed++;
  }
  // saved ones load from disk from now on; unsaved ones stay for undo/redo
  for (const path of [...pending.keys()]) {
    if (path.startsWith(prefix) && referenced.includes(path)) {
      URL.revokeObjectURL(pending.get(path)!.url);
      pending.delete(path);
    }
  }
  return { written, removed };
}

// ------------------------------------------------------------------ overrides
// A mod replaces any game image by shipping mods/<mod>/overrides/<rel> for
// assets/generated/<rel> (gen1recomp src/render/Assets.lua resolve). The
// image_overrides records are rel -> content hash of the replacement; the
// bytes of imported ones stay in memory (by hash, so undo/redo can go back
// to any of them) until a save writes them. "disk" = the file already there.

export const OVERRIDES = "image_overrides";
const overridePending = new Map<string, { data: Uint8Array; url: string }>();
// what each override file holds since the last save (path -> hash)
const overrideSaved = new Map<string, string>();

export function overridePath(mod: string, rel: string): string {
  return `mods/${mod}/overrides/${rel}`;
}

// keeps an imported replacement; returns the hash its record holds
export function addOverride(data: Uint8Array): string {
  const h = hash(data);
  if (!overridePending.has(h)) overridePending.set(h, { data, url: URL.createObjectURL(new Blob([data as BlobPart], { type: "image/png" })) });
  return h;
}

export function overrideUrl(host: Host, version: string, mod: string, rel: string, value: string): string {
  const pend = overridePending.get(value)?.url;
  if (pend) return pend;
  const url = host.imageUrl(version, overridePath(mod, rel));
  return `${url}${url.includes("?") ? "&" : "?"}v=${encodeURIComponent(value)}`;
}

// Every override file below mods/<mod>/overrides/ (PNG), as rel paths.
export async function listOverrides(host: Host, mod: string): Promise<string[]> {
  const out: string[] = [];
  const walk = async (dir: string, depth: number): Promise<void> => {
    if (depth > 6) return;
    for (const e of await host.list("game", `mods/${mod}/overrides${dir ? `/${dir}` : ""}`)) {
      const rel = dir ? `${dir}/${e.name}` : e.name;
      if (e.dir) await walk(rel, depth + 1);
      else if (e.name.toLowerCase().endsWith(".png")) out.push(rel);
    }
  };
  await walk("", 0);
  return out.sort();
}

// Writes the recorded replacements that are new and removes override PNGs
// no record keeps.
export async function saveOverrides(host: Host, mod: string, records: Record<string, unknown>): Promise<{ written: number; removed: number }> {
  let written = 0;
  let removed = 0;
  for (const [rel, value] of Object.entries(records)) {
    const pend = typeof value === "string" ? overridePending.get(value) : undefined;
    const path = overridePath(mod, rel);
    if (!pend || overrideSaved.get(path) === value) continue;
    await host.writeBinary(path, pend.data);
    overrideSaved.set(path, value as string);
    written++;
  }
  for (const rel of await listOverrides(host, mod)) {
    if (records[rel] !== undefined) continue;
    await host.deleteFile(overridePath(mod, rel));
    overrideSaved.delete(overridePath(mod, rel));
    removed++;
  }
  return { written, removed };
}
